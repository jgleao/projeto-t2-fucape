-- =============================================================================
-- DATA WAREHOUSE - Modelo Estrela (Kimball)
--
-- GRANULARIDADE DA FATO dw.fato_review:
--   "Cada linha representa UMA review publicada por um jogador sobre um jogo
--    na Steam, na data em que a review foi criada."
--
-- Dimensoes (todas com Surrogate Key inteira, desacoplada da chave natural):
--   dim_tempo          sk_tempo   - calendario (data de criacao da review)
--   dim_jogo           sk_jogo    - jogo avaliado            (NK: app_id)
--   dim_autor          sk_autor   - jogador que escreveu     (NK: steamid)
--   dim_perfil_review  sk_perfil  - junk dimension de flags  (recomendado, compra, ...)
--   dim_review         sk_review  - texto da review (corpus da busca)  (NK: recommendationid)
--
-- Membro "desconhecido" sk = -1 em cada dimensao (padrao Kimball): a fato nunca
-- fica com FK nula nem orfa.
-- Todas as instrucoes sao idempotentes (IF NOT EXISTS / ON CONFLICT DO NOTHING).
-- =============================================================================
CREATE SCHEMA IF NOT EXISTS stg;
CREATE SCHEMA IF NOT EXISTS dw;

-- --------------------------------------------------------------- STAGING ---
-- Area de trabalho do DAG 2: reviews limpas, tipadas e desaninhadas da execucao
-- corrente. E truncada e recarregada a cada execucao (idempotente).
CREATE TABLE IF NOT EXISTS stg.reviews (
    recommendationid        TEXT PRIMARY KEY,
    app_id                  INTEGER NOT NULL,
    steamid                 TEXT,
    autor_qtd_jogos         INTEGER,
    autor_qtd_reviews       INTEGER,
    minutos_jogados_total   INTEGER,
    minutos_jogados_review  INTEGER,
    idioma                  TEXT,
    criado_em               TIMESTAMP NOT NULL,
    atualizado_em           TIMESTAMP,
    recomendado             BOOLEAN NOT NULL,
    compra_steam            BOOLEAN NOT NULL,
    recebido_gratis         BOOLEAN NOT NULL,
    acesso_antecipado       BOOLEAN NOT NULL,
    steam_deck              BOOLEAN NOT NULL,
    votos_uteis             INTEGER NOT NULL,
    votos_engracados        INTEGER NOT NULL,
    qtd_comentarios         INTEGER NOT NULL,
    score_utilidade         NUMERIC(12, 10),
    texto_original          TEXT,
    texto_limpo             TEXT,
    qtd_palavras            INTEGER NOT NULL,
    qtd_caracteres          INTEGER NOT NULL
);

-- ---------------------------------------------------------- DIM_TEMPO ------
CREATE TABLE IF NOT EXISTS dw.dim_tempo (
    sk_tempo        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_completa   DATE UNIQUE,            -- NULL apenas no membro desconhecido
    ano             INTEGER,
    semestre        INTEGER,
    trimestre       INTEGER,
    mes             INTEGER,
    nome_mes        TEXT,
    ano_mes         TEXT,                   -- 'AAAA-MM' (ordenavel)
    dia             INTEGER,
    dia_semana_num  INTEGER,                -- ISO: 1 = segunda ... 7 = domingo
    dia_semana      TEXT,
    fim_de_semana   BOOLEAN,
    semana_ano      INTEGER
);

-- ----------------------------------------------------------- DIM_JOGO ------
CREATE TABLE IF NOT EXISTS dw.dim_jogo (
    sk_jogo           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id            INTEGER NOT NULL UNIQUE,       -- chave natural (Steam)
    nome_jogo         TEXT NOT NULL,
    tipo              TEXT,
    desenvolvedor     TEXT,
    publicadora       TEXT,
    genero_principal  TEXT,
    generos           TEXT,                          -- lista desnormalizada "Acao, RPG"
    gratuito          BOOLEAN,
    preco_base_brl    NUMERIC(10, 2),
    data_lancamento   DATE,
    ano_lancamento    INTEGER,
    descricao_curta   TEXT,
    atualizado_em     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------- DIM_AUTOR ------
CREATE TABLE IF NOT EXISTS dw.dim_autor (
    sk_autor            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    steamid             TEXT NOT NULL UNIQUE,        -- chave natural (Steam)
    qtd_jogos_possuidos INTEGER,
    qtd_reviews_escritas INTEGER,
    faixa_biblioteca    TEXT,                        -- faixa de tamanho da biblioteca
    perfil_avaliador    TEXT,                        -- faixa de experiencia como avaliador
    atualizado_em       TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------- DIM_PERFIL_REVIEW ------
-- Junk dimension: agrupa flags de baixa cardinalidade (2^5 = 32 combinacoes).
CREATE TABLE IF NOT EXISTS dw.dim_perfil_review (
    sk_perfil          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recomendado        BOOLEAN,
    compra_steam       BOOLEAN,
    recebido_gratis    BOOLEAN,
    acesso_antecipado  BOOLEAN,
    steam_deck         BOOLEAN,
    desc_recomendacao  TEXT,
    desc_aquisicao     TEXT,
    desc_fase_jogo     TEXT,
    desc_plataforma    TEXT,
    UNIQUE (recomendado, compra_steam, recebido_gratis, acesso_antecipado, steam_deck)
);

-- --------------------------------------------------------- DIM_REVIEW ------
CREATE TABLE IF NOT EXISTS dw.dim_review (
    sk_review         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendationid  TEXT NOT NULL UNIQUE,          -- chave natural (Steam)
    idioma            TEXT,
    texto_original    TEXT,
    texto_limpo       TEXT,                          -- sem BBCode/URLs: corpus da busca
    qtd_palavras      INTEGER,
    faixa_tamanho     TEXT,
    atualizado_em     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- -------------------------------------------------------- FATO_REVIEW ------
CREATE TABLE IF NOT EXISTS dw.fato_review (
    sk_fato                  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    recommendationid         TEXT NOT NULL UNIQUE,   -- dimensao degenerada (chave da carga idempotente)
    sk_tempo                 INTEGER NOT NULL REFERENCES dw.dim_tempo (sk_tempo),
    sk_jogo                  INTEGER NOT NULL REFERENCES dw.dim_jogo (sk_jogo),
    sk_autor                 INTEGER NOT NULL REFERENCES dw.dim_autor (sk_autor),
    sk_perfil                INTEGER NOT NULL REFERENCES dw.dim_perfil_review (sk_perfil),
    sk_review                INTEGER NOT NULL REFERENCES dw.dim_review (sk_review),
    -- metricas aditivas
    qtd_reviews              INTEGER NOT NULL,        -- sempre 1 (contagem)
    qtd_recomendacoes        INTEGER NOT NULL,        -- 1 se recomendou
    qtd_nao_recomendacoes    INTEGER NOT NULL,        -- 1 se nao recomendou
    votos_uteis              INTEGER NOT NULL,
    votos_engracados         INTEGER NOT NULL,
    qtd_comentarios          INTEGER NOT NULL,
    minutos_jogados_review   INTEGER NOT NULL,        -- tempo de jogo no momento da review
    qtd_palavras             INTEGER NOT NULL,
    -- metrica semiaditiva (foto do tempo total na data da coleta)
    minutos_jogados_total    INTEGER NOT NULL,
    -- metrica nao aditiva (usar media, nunca soma)
    score_utilidade          NUMERIC(12, 10),
    carregado_em             TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_fato_tempo  ON dw.fato_review (sk_tempo);
CREATE INDEX IF NOT EXISTS ix_fato_jogo   ON dw.fato_review (sk_jogo);
CREATE INDEX IF NOT EXISTS ix_fato_autor  ON dw.fato_review (sk_autor);
CREATE INDEX IF NOT EXISTS ix_fato_perfil ON dw.fato_review (sk_perfil);

-- ------------------------------------------------- CONTROLE DO ETL ---------
CREATE TABLE IF NOT EXISTS dw.etl_controle (
    processo     TEXT PRIMARY KEY,
    watermark    TIMESTAMPTZ NOT NULL,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS dw.etl_execucao (
    run_id              TEXT PRIMARY KEY,
    linhas_staging      INTEGER,
    fato_inseridas      INTEGER,
    fato_atualizadas    INTEGER,
    total_fato          BIGINT,
    soma_votos_uteis    BIGINT,
    checks              JSONB,
    status              TEXT,
    finalizado_em       TIMESTAMPTZ NOT NULL DEFAULT now()
);

